#!/bin/sh
# ==============================================================================
# 脚本名称: autoremove_log_ubuntu_home_marco.sh
# 脚本说明: Ubuntu 主机专用日志清理与历史备份保底清理脚本
# 适用主机: ubuntu_home_marco
# 推荐配置: 放入系统定时任务（Cron），每日凌晨定期执行（如 03:30）
# ==============================================================================

# ------------------------------------------------------------------------------
# 1. 清理 FRP 客户端日志
# ------------------------------------------------------------------------------
rm -f /opt/frp/frpc.*.log 2>/dev/null || true

# ------------------------------------------------------------------------------
# 2. 截断备份日志，防止长期运行日志无限增长占满磁盘
# ------------------------------------------------------------------------------
[ -f /home/backups/backup.log ] && cat /dev/null > /home/backups/backup.log
[ -f /home/backups/backup_openwrt.log ] && cat /dev/null > /home/backups/backup_openwrt.log

# ------------------------------------------------------------------------------
# 3. 独立保底清理机制（防止主备份脚本异常中断未清理导致满盘）
# 3.1 自动删除 /home/backups 下修改时间超过 14 天的备份归档文件（.tgz, .enc, .tar.gz）
# 3.2 自动删除 /home/backups/temp 下修改时间超过 2 天的遗留临时 SQL 转储文件
# ------------------------------------------------------------------------------
find /home/backups -maxdepth 1 \( -name "*.tgz" -o -name "*.enc" -o -name "*.tar.gz" \) -type f -mtime +14 -delete 2>/dev/null || true
find /home/backups/temp -maxdepth 1 -name "*.sql" -type f -mtime +2 -delete 2>/dev/null || true
